    /// 표마다 문서가 밝힌 개수 · 대문자 · 중복 0.
    #[test]
    fn tables_match_documented_counts() {
        for (name, t, n) in [
            ("ORACLE_RESERVED", ORACLE_RESERVED, 110),
            ("ORACLE_PLSQL_RESERVED", ORACLE_PLSQL_RESERVED, 85),
            ("MSSQL_RESERVED", MSSQL_RESERVED, 185),
            ("PG_RESERVED", PG_RESERVED, 78),
            ("PG_RESERVED_FN_TYPE_OK", PG_RESERVED_FN_TYPE_OK, 23),
            ("PG_NONRESERVED_NOT_FN_TYPE", PG_NONRESERVED_NOT_FN_TYPE, 55),
            ("PG_NONRESERVED_REQUIRES_AS", PG_NONRESERVED_REQUIRES_AS, 11),
            ("SQLITE_KEYWORDS", SQLITE_KEYWORDS, 147),
            ("MYSQL_RESERVED", MYSQL_RESERVED, 260),
            ("ANSI2016_RESERVED", ANSI2016_RESERVED, 398),
            ("ANSI2016_NONRESERVED", ANSI2016_NONRESERVED, 297),
            ("ANSI2023_RESERVED_ADDED", ANSI2023_RESERVED_ADDED, 11),
            ("ANSI2023_NONRESERVED_ADDED", ANSI2023_NONRESERVED_ADDED, 1),
        ] {
            assert_eq!(t.len(), n, "{name} 개수");
            let mut seen = std::collections::HashSet::new();
            for w in t {
                assert_eq!(*w, w.to_ascii_uppercase(), "{name} 대문자 {w}");
                assert!(seen.insert(*w), "{name} 중복 {w}");
            }
        }
    }

    /// 108 §9 #8 재현 낱말: Oracle `LEVEL` · MySQL `KEY` · SQL Server `KEY` = 예약 · PostgreSQL `KEY` = 비예약(인용 불필요) · `USER`는 PG 예약.
    #[test]
    fn dialect_specific_reserved_words() {
        assert!(is_reserved(Dialect::Oracle, "level"));
        assert!(is_reserved(Dialect::Oracle, "COLUMN"));
        assert!(!is_reserved(Dialect::Oracle, "KEY"));
        assert!(is_reserved(Dialect::Mysql, "KEY"));
        assert!(is_reserved(Dialect::Mssql, "Key"));
        assert!(!is_reserved(Dialect::Postgres, "KEY"));
        assert!(is_reserved(Dialect::Postgres, "USER"));
        assert!(
            is_reserved(Dialect::Postgres, "LEFT"),
            "함수·형 자리 허용 예약도 열 이름은 인용"
        );
        assert!(is_reserved(Dialect::Duckdb, "USER"));
        assert!(is_reserved(Dialect::Sqlite, "KEY"));
        assert!(is_reserved(Dialect::Odbc, "SELECT"));
        assert!(!is_reserved(Dialect::Odbc, "ITEM_CD"));
        assert!(!is_reserved(Dialect::Oracle, ""));
        assert_eq!(reserved_words(Dialect::Mysql).len(), 260);
    }
