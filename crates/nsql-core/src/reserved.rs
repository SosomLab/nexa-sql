//! 한 벌을 모든 방언에 재사용(108 §9 #7·#8) → 열 이름 `LEVEL`(Oracle) · `KEY`(MySQL) 같은 방언 예약어가 따옴표 없이 나가 실행이 깨졌다.
//!
//! 표 = docs/108(각 DBMS T-3) · docs/109 §14(ANSI)에서 협업이 기계 추출(2026-11-03 · 개수 = 문서 명시와 일치 · 대문자 · 정렬 · 중복 0 ·
//! 추측 채움 0 · 원천 URL = 각 표 머리). 문서에 전체 낱말이 없는 것(PostgreSQL 일반 non-reserved ≈300 · SQLite fallback 전체 ·
//! SQL Server 향후/ODBC 예약 · MySQL 비예약 · Oracle V$RESERVED_WORDS 키워드)은 넣지 않았다 — 인용 판정은 "예약어면 인용"이라
//! 빠진 쪽은 인용이 **덜** 되는 쪽이므로, 호출자는 종전 포맷터 키워드 표와 합집합으로 쓴다(인용이 줄지 않게).
//!
//! 의존 0(std만) · 조회 = 선형(표 ≤ 400 · 열 이름 하나 판정할 때만).

use crate::Dialect;

/// 이 방언에서 **따옴표 없이 식별자로 쓸 수 없는** 낱말인가(예약어 · 대소문자 무시 · 방언 모르면 ANSI 2016/2023 예약어).
///
/// 방언 매핑: Oracle = SQL 예약어(PL/SQL 예약어는 블록 안 이름용이라 제외) · SQL Server = T-SQL 예약어 · PostgreSQL = 예약 + 함수·형
/// 자리에서만 허용되는 예약(둘 다 열 이름으로는 인용 필요) · DuckDB = PostgreSQL 표(문법 계열 같음) · SQLite = 키워드 147(fallback으로
/// 식별자가 되기도 하나 인용이 안전) · MySQL = 8.0 예약(R) · Db2 · ODBC · Access · ClickHouse = ANSI 예약(2016 + 2023 추가).
#[must_use]
pub fn is_reserved(dialect: Dialect, word: &str) -> bool {
    let w = word.trim();
    if w.is_empty() {
        return false;
    }
    let hit = |t: &[&str]| t.iter().any(|k| k.eq_ignore_ascii_case(w));
    match dialect {
        Dialect::Oracle => hit(ORACLE_RESERVED),
        Dialect::Mssql => hit(MSSQL_RESERVED),
        Dialect::Postgres | Dialect::Duckdb => hit(PG_RESERVED) || hit(PG_RESERVED_FN_TYPE_OK),
        Dialect::Sqlite => hit(SQLITE_KEYWORDS),
        Dialect::Mysql => hit(MYSQL_RESERVED),
        Dialect::Db2 | Dialect::Odbc | Dialect::Access | Dialect::Clickhouse => {
            hit(ANSI2016_RESERVED) || hit(ANSI2023_RESERVED_ADDED)
        }
    }
}

/// 이 방언의 예약어 표(대문자) — 완성·강조기가 방언 키워드로 쓸 때(T-78 · T-325 잔여).
#[must_use]
pub fn reserved_words(dialect: Dialect) -> &'static [&'static str] {
    match dialect {
        Dialect::Oracle => ORACLE_RESERVED,
        Dialect::Mssql => MSSQL_RESERVED,
        Dialect::Postgres | Dialect::Duckdb => PG_RESERVED,
        Dialect::Sqlite => SQLITE_KEYWORDS,
        Dialect::Mysql => MYSQL_RESERVED,
        Dialect::Db2 | Dialect::Odbc | Dialect::Access | Dialect::Clickhouse => ANSI2016_RESERVED,
    }
}

